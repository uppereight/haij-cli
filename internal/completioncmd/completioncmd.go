// Package completioncmd implements the `haij completion <shell>`
// subcommand. The Homebrew formula (Formula/haij.rb) calls
// `generate_completions_from_executable(bin/"haij", "completion")`
// at install time, which expects the binary to emit a valid
// completion script on stdout for each of bash / zsh / fish.
//
// The scripts are intentionally minimal — they list the top-level
// subcommands and the global flags. Per-subcommand argument
// completion (e.g. flag values) is out of scope; users who want
// rich completions should rely on `haij commands` or the
// embedded SKILL.md.
//
// Spec 30 Phase 3 — see test #4 (Homebrew formula install path)
// and the formula's `def install` block in Formula/haij.rb.
package completioncmd

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/uppereight/haij-cli/internal/catalog"
	"github.com/uppereight/haij-cli/internal/envelope"
)

// SupportedShells is the set of shells emitted by `haij completion`.
// The order is canonical; tests assert on it.
var SupportedShells = []string{"bash", "zsh", "fish"}

// Run handles `haij completion <shell>`. Returns a process exit code:
//
//	0 on success — script written to stdout
//	1 on usage error — message written to stderr
//	2 on unknown shell — message + supported list to stderr
//
// jsonMode is honored only on usage errors so callers piping into a
// JSON pipeline (e.g. `haij completion --json`) still get a parseable
// envelope when the invocation is malformed. The actual completion
// scripts are emitted as plain text — they have to be sourced by the
// shell, which would choke on JSON.
func Run(args []string, jsonMode bool, stdout, stderr io.Writer) int {
	if len(args) < 1 {
		return usageError("missing shell argument", jsonMode, stdout, stderr)
	}
	shell := strings.ToLower(args[0])

	script, ok := scripts[shell]
	if !ok {
		return unknownShellError(shell, jsonMode, stdout, stderr)
	}

	fmt.Fprint(stdout, script)
	return 0
}

// topLevelCommands returns the canonical top-level subcommand names.
// Source-of-truth: catalog.All() filtered to the first segment after
// `haij `. Sorted, deduped.
func topLevelCommands() []string {
	seen := make(map[string]struct{})
	for _, c := range catalog.All().Commands {
		// Catalog entries look like "haij forms list"; we only want
		// "forms" for top-level completion. Skip flag-like names
		// such as "haij --help" / "haij --version" — those are
		// rendered into the globals list separately.
		parts := strings.Fields(c.Name)
		if len(parts) >= 2 && !strings.HasPrefix(parts[1], "-") {
			seen[parts[1]] = struct{}{}
		}
	}
	// `commands` and `completion` are top-level introspection commands
	// not currently in the catalog payload but always present.
	seen["commands"] = struct{}{}
	seen["completion"] = struct{}{}
	out := make([]string, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// scripts is the in-memory rendering of each shell's completion
// script. Built once at package init from the live catalog so adding
// a new top-level command is automatically reflected.
var scripts = renderAll()

func renderAll() map[string]string {
	cmds := topLevelCommands()
	cmdList := strings.Join(cmds, " ")
	return map[string]string{
		"bash": renderBash(cmdList),
		"zsh":  renderZsh(cmdList),
		"fish": renderFish(cmds),
	}
}

func renderBash(cmdList string) string {
	return fmt.Sprintf(`# bash completion for haij — generated by `+"`haij completion bash`"+`
_haij_completions() {
  local cur="${COMP_WORDS[COMP_CWORD]}"
  local prev="${COMP_WORDS[COMP_CWORD-1]}"
  local cmds="%s"
  local globals="--help --version --json --profile --agent"
  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=( $(compgen -W "${cmds} ${globals}" -- "${cur}") )
    return 0
  fi
  COMPREPLY=( $(compgen -W "${globals}" -- "${cur}") )
}
complete -F _haij_completions haij
`, cmdList)
}

func renderZsh(cmdList string) string {
	return fmt.Sprintf(`#compdef haij
# zsh completion for haij — generated by `+"`haij completion zsh`"+`
_haij() {
  local -a cmds globals
  cmds=(%s)
  globals=(--help --version --json --profile --agent)
  if (( CURRENT == 2 )); then
    _describe 'subcommand' cmds
    _describe 'global flag' globals
  else
    _describe 'global flag' globals
  fi
}
_haij "$@"
`, cmdList)
}

func renderFish(cmds []string) string {
	var b strings.Builder
	b.WriteString("# fish completion for haij — generated by `haij completion fish`\n")
	b.WriteString("complete -c haij -f\n")
	for _, c := range cmds {
		b.WriteString(fmt.Sprintf("complete -c haij -n \"__fish_use_subcommand\" -a %q\n", c))
	}
	for _, g := range []string{"help", "version", "json", "profile", "agent"} {
		b.WriteString(fmt.Sprintf("complete -c haij -l %s\n", g))
	}
	return b.String()
}

func usageError(msg string, jsonMode bool, stdout, stderr io.Writer) int {
	if jsonMode {
		env := envelope.Failure(
			"completion_usage",
			msg+" — usage: haij completion <"+strings.Join(SupportedShells, "|")+">",
			map[string]any{"supported_shells": SupportedShells},
		)
		out, _ := envelope.Render(env)
		fmt.Fprintln(stdout, string(out))
		return 1
	}
	fmt.Fprintf(stderr, "haij completion: %s\nusage: haij completion <%s>\n",
		msg, strings.Join(SupportedShells, "|"))
	return 1
}

func unknownShellError(shell string, jsonMode bool, stdout, stderr io.Writer) int {
	if jsonMode {
		env := envelope.Failure(
			"completion_unknown_shell",
			fmt.Sprintf("unknown shell %q — supported: %s", shell, strings.Join(SupportedShells, ", ")),
			map[string]any{"shell": shell, "supported_shells": SupportedShells},
		)
		out, _ := envelope.Render(env)
		fmt.Fprintln(stdout, string(out))
		return 2
	}
	fmt.Fprintf(stderr, "haij completion: unknown shell %q (supported: %s)\n",
		shell, strings.Join(SupportedShells, ", "))
	return 2
}

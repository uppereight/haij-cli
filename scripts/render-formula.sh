#!/usr/bin/env bash
# Prints Formula/haij.rb for one release, taking each archive's checksum
# from that release's SHA256SUMS. release.sh attaches the output to the
# GitHub release as haij.rb; commit that file after a release:
#
#   gh release download v0.1.0 --pattern haij.rb --output Formula/haij.rb --clobber
set -euo pipefail

usage="usage: scripts/render-formula.sh <version, no leading v> <SHA256SUMS>"
version=${1:?$usage}
sums=${2:?$usage}

sum() {
  local file="haij-$version-$1.tar.gz" hash
  hash=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [[ ! $hash =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-formula.sh: no sha256 for $file in $sums" >&2
    exit 1
  fi
  echo "$hash"
}
darwin_arm64=$(sum darwin-arm64)
darwin_amd64=$(sum darwin-amd64)
linux_arm64=$(sum linux-arm64)
linux_amd64=$(sum linux-amd64)

cat <<RUBY
# Homebrew formula for haij $version. Generated by scripts/render-formula.sh
# from the release's SHA256SUMS; do not edit by hand. Every tagged release
# attaches a fresh copy as haij.rb.
#
# This repository doubles as the tap. Once it is public:
#
#   brew tap uppereight/haij-cli https://github.com/uppereight/haij-cli
#   brew install haij
class Haij < Formula
  desc "Command-line client and MCP server for the haij form and workflow platform"
  homepage "https://github.com/uppereight/haij-cli"
  version "$version"

  on_macos do
    on_arm do
      url "https://github.com/uppereight/haij-cli/releases/download/v#{version}/haij-#{version}-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "https://github.com/uppereight/haij-cli/releases/download/v#{version}/haij-#{version}-darwin-amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/uppereight/haij-cli/releases/download/v#{version}/haij-#{version}-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "https://github.com/uppereight/haij-cli/releases/download/v#{version}/haij-#{version}-linux-amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "haij"
    generate_completions_from_executable(bin/"haij", "completion")
  end

  test do
    assert_match "haij #{version} (", shell_output("#{bin}/haij --version")
    assert_match(/multi-tenant form & workflow CLI/i, shell_output("#{bin}/haij --help"))
  end
end
RUBY
